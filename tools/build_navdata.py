#!/usr/bin/env python3
"""Writes src/data/navdata.js from OurAirports' public domain data (https://ourairports.com/data/):
the radio beacons (VOR, VOR-DME, VORTAC, DME, NDB, NDB-DME) for the ND's VOR.D and NDB buttons and the RMP's
navigation receivers, and the airports' radio frequencies (ATIS, TWR, APP, GND, DEL, CTAF) for the radio management
panels, keyed by the game's airport codes (IATA, else the ICAO ident).

    python tools/build_navdata.py <folder with navaids.csv, airport-frequencies.csv and airports.csv>

The CSVs: https://davidmegginson.github.io/ourairports-data/{navaids,airport-frequencies,airports}.csv
"""
import csv
import json
import os
import re
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
src = sys.argv[1] if len(sys.argv) > 1 else '.'

# the game's airport codes (hand-made ones and the generated ones)
codes = set()
for name in ('airports.js', 'airports-more.js'):
    with open(os.path.join(ROOT, 'flightgame', 'js', 'data', name), encoding='utf-8') as f:
        text = f.read()
    codes.update(re.findall(r"code: '([A-Z0-9]{3,4})'", text))
    codes.update(re.findall(r'\["([A-Z0-9]{3,4})",', text))

# OurAirports ident -> the game's code
ident_to_code = {}
with open(os.path.join(src, 'airports.csv'), encoding='utf-8') as f:
    for r in csv.DictReader(f):
        iata, ident = (r['iata_code'] or '').strip(), r['ident'].strip()
        if iata and iata in codes:
            ident_to_code.setdefault(ident, iata)
        elif ident in codes:
            ident_to_code.setdefault(ident, ident)

KINDS = {'ATIS': 'ATIS', 'D-ATIS': 'ATIS', 'TWR': 'TWR', 'TOWER': 'TWR', 'APP': 'APP', 'APPROACH': 'APP',
         'GND': 'GND', 'GROUND': 'GND', 'DEL': 'DEL', 'CLD': 'DEL', 'CTAF': 'CTAF', 'DEP': 'DEP'}
freqs = {}
with open(os.path.join(src, 'airport-frequencies.csv'), encoding='utf-8') as f:
    for r in csv.DictReader(f):
        code = ident_to_code.get(r['airport_ident'].strip())
        kind = KINDS.get((r['type'] or '').strip().upper())
        if not code or not kind:
            continue
        try:
            mhz = round(float(r['frequency_mhz']), 3)
        except ValueError:
            continue
        if not 108 <= mhz <= 137:
            continue
        lst = freqs.setdefault(code, [])
        if not any(k == kind and m == mhz for k, m in lst):
            lst.append([kind, mhz])

TYPES = {'VOR': 'V', 'VOR-DME': 'VD', 'VORTAC': 'VD', 'DME': 'D', 'TACAN': None, 'NDB': 'N', 'NDB-DME': 'N'}
navaids = []
with open(os.path.join(src, 'navaids.csv'), encoding='utf-8') as f:
    for r in csv.DictReader(f):
        t = TYPES.get(r['type'])
        if not t:
            continue
        try:
            khz = float(r['frequency_khz'])
            lat, lon = float(r['latitude_deg']), float(r['longitude_deg'])
        except ValueError:
            continue
        # VOR and DME in MHz (108.00 - 117.95), NDB in kHz
        freq = round(khz / 1000, 2) if t != 'N' else round(khz)
        name = (r['name'] or '').strip().title()
        navaids.append([r['ident'].strip(), t, freq, round(lat, 4), round(lon, 4), name])

out = os.path.join(ROOT, 'src', 'data', 'navdata.js')
os.makedirs(os.path.dirname(out), exist_ok=True)
with open(out, 'w', encoding='utf-8') as f:
    f.write('// Generated by tools/build_navdata.py from OurAirports (public domain). Do not edit by hand.\n')
    f.write('// navaids: [ident, kind (V VOR, VD VOR-DME, D DME, N NDB), MHz (VOR/DME) or kHz (NDB), lat, lon, name]\n')
    f.write('// freqs: airport code -> [[ATIS|TWR|APP|GND|DEL|DEP|CTAF, MHz], ...]\n')
    f.write('FG.navdata = {\nnavaids: [\n')
    f.write(',\n'.join(json.dumps(n, ensure_ascii=False, separators=(',', ':')) for n in navaids))
    f.write('\n],\nfreqs: {\n')
    f.write(',\n'.join(f'"{k}":{json.dumps(v, separators=(",", ":"))}' for k, v in sorted(freqs.items())))
    f.write('\n}};\n')
print(f'{len(navaids)} navaids, frequencies for {len(freqs)} of {len(codes)} airports -> {os.path.relpath(out, ROOT)}'
      f' ({os.path.getsize(out) // 1024} kB)')
